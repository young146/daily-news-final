// 검색어를 낱말로 쪼개는 규칙 — **여기 한 곳에서만 정의한다.**
//
// 왜 한 곳인가 (2026-08-08 실제로 물린 일):
//   통합검색(/api/search)과 AI 도우미의 search_directory 가 각자 자기 SQL 을 갖고 있었다.
//   /api/search 만 낱말 쪼개기로 고쳤더니 **"웹에선 찾아지는데 AI 는 못 찾는"** 상태가 됐다.
//   같은 규칙을 두 벌로 두면 반드시 한쪽만 고쳐진다. 그래서 규칙을 이 파일로 끌어냈다.
//   새로 검색을 쓰는 곳이 생기면 여기를 import 할 것. 자기 버전을 새로 만들지 말 것.

// 군말 — 검색에서 아무 것도 걸러주지 못하는 낱말들.
// 남겨두면 이 단어만 스친 엉뚱한 데이터가 딸려온다.
// '베트남'도 버린다: 이 데이터는 전부 베트남 것이라 구분에 전혀 도움이 안 된다.
export const SEARCH_STOPWORDS = new Set([
  "정보", "안내", "추천", "관련", "대한", "대해", "소개", "목록", "리스트", "종류", "방법",
  "알려줘", "알려주세요", "찾아줘", "찾아주세요", "가르쳐줘", "해줘", "주세요", "부탁",
  "어디", "어디야", "어디에", "어디서", "좋은", "괜찮은", "유명한", "제일", "가장", "많이",
  "있나요", "있어", "있을까", "뭐야", "뭐가", "무엇", "어떤", "어떻게", "얼마", "언제",
  "베트남", "베트남에", "베트남의", "한국", "우리", "저희", "그리고", "또는", "그런",
  // ── 연결어·꾸밈말 (2026-08-08 추가) ─────────────────────────────────
  // "베트남 진출을 위한 컨설팅업체" 로 검색했더니 뉴스 2,048건 · 매거진 2,521건이 잡혔다.
  // 범인은 **"위한"** — "~을 위한" 은 기사 수천 개에 들어 있어 아무 것도 걸러주지 못한다.
  // 이런 말은 문장에서 자연스러울수록 검색에서는 해롭다.
  "위한", "위해", "위하여", "통해", "통한", "관한", "따른", "따라",
  "하는", "되는", "있는", "없는", "같은", "다른", "여러", "모든", "어느", "무슨",
  "이런", "저런", "그것", "이것", "저것", "때문", "경우", "정도", "이상", "이하",
]);

// 끝에 붙은 조사. 3글자 이상인 낱말에서만 뗀다 —
// "요가"의 '가'까지 떼면 검색어 자체가 사라진다.
const PARTICLE = /(으로|에서|에게|은|는|이|가|을|를|의|에|와|과|로|도|만)$/;

// "소개해줘", "알려주세요" 처럼 **부탁하는 말꼬리**. 떼고 나면 대개 군말만 남아 걸러진다.
// 새 홈이 문장 입력을 권하므로 이런 말꼬리가 자주 들어온다.
const REQUEST_TAIL = /(해주세요|해줄래|해줘|알려주세요|알려줘|찾아주세요|찾아줘|주세요|할까요|할까|하나요|인가요|일까요|입니까|인가|일까)$/;

/**
 * 검색어 → 실제로 훑을 낱말 배열.
 *   "베트남 구인구직 안내 정보"  → ["구인구직"]
 *   "2군에 평점 좋은 한식당 알려줘" → ["2군", "평점", "한식당"]
 *   "요가 학원"                   → ["요가", "학원"]
 * 최대 5개 — 너무 잘게 쪼개면 무관한 결과가 급격히 늘어난다.
 */
export function searchTerms(input) {
  const out = [];
  for (let t of String(input || "").split(/[\s,./·|()[\]{}"'`~!?]+/)) {
    t = t.trim();
    if (!t) continue;
    if (t.length >= 3) t = t.replace(REQUEST_TAIL, "");   // "소개해줘" → "소개" → 아래에서 군말로 걸러짐
    if (t.length >= 3) t = t.replace(PARTICLE, "");
    if (t.length < 2 || SEARCH_STOPWORDS.has(t)) continue;
    if (!out.includes(t)) out.push(t);                     // 같은 낱말 두 번 세지 않는다
    if (out.length >= 5) break;
  }
  return out;
}

/**
 * 낱말이 여러 개일 때 **몇 개 이상 맞아야 결과로 볼 것인가.**
 *
 * 왜 필요한가: 낱말을 OR 로만 묶으면 흔한 낱말 하나에 스친 기사가 수천 건 딸려온다
 * (실측: "베트남 진출을 위한 컨설팅업체를 소개해줘" → 뉴스 2,048 · 매거진 2,521).
 * 낱말이 2개 이상이면 **최소 2개는 맞아야** 후보로 본다. 한 낱말만 스친 것은 대개 무관하다.
 * 낱말이 하나뿐이면 그대로 1 — 좁힐 여지가 없다.
 */
export function minTermHits(terms) {
  return terms.length >= 2 ? 2 : 1;
}
