// 검색어를 낱말로 쪼개는 규칙 — **여기 한 곳에서만 정의한다.**
//
// 왜 한 곳인가 (2026-08-08 실제로 물린 일):
//   통합검색(/api/search)과 AI 도우미의 search_directory 가 각자 자기 SQL 을 갖고 있었다.
//   /api/search 만 낱말 쪼개기로 고쳤더니 **"웹에선 찾아지는데 AI 는 못 찾는"** 상태가 됐다.
//   같은 규칙을 두 벌로 두면 반드시 한쪽만 고쳐진다. 그래서 규칙을 이 파일로 끌어냈다.
//   새로 검색을 쓰는 곳이 생기면 여기를 import 할 것. 자기 버전을 새로 만들지 말 것.

// 군말 — 검색에서 아무 것도 걸러주지 못하는 낱말들.
// 남겨두면 이 단어만 스친 엉뚱한 데이터가 딸려온다.
// '베트남'도 버린다: 이 데이터는 전부 베트남 것이라 구분에 전혀 도움이 안 된다.
export const SEARCH_STOPWORDS = new Set([
  "정보", "안내", "추천", "관련", "대한", "대해", "소개", "목록", "리스트", "종류",
  "알려줘", "알려주세요", "찾아줘", "찾아주세요", "가르쳐줘", "해줘", "주세요", "부탁",
  "어디", "어디야", "어디에", "어디서", "좋은", "괜찮은", "유명한", "제일", "가장",
  "있나요", "있어", "있을까", "뭐야", "뭐가", "무엇", "어떤", "어떻게",
  "베트남", "베트남에", "베트남의", "한국", "우리", "저희", "그리고", "또는", "그런",
]);

// 끝에 붙은 조사. 3글자 이상인 낱말에서만 뗀다 —
// "요가"의 '가'까지 떼면 검색어 자체가 사라진다.
const PARTICLE = /(으로|에서|에게|은|는|이|가|을|를|의|에|와|과|로|도|만)$/;

/**
 * 검색어 → 실제로 훑을 낱말 배열.
 *   "베트남 구인구직 안내 정보"  → ["구인구직"]
 *   "2군에 평점 좋은 한식당 알려줘" → ["2군", "평점", "한식당"]
 *   "요가 학원"                   → ["요가", "학원"]
 * 최대 5개 — 너무 잘게 쪼개면 무관한 결과가 급격히 늘어난다.
 */
export function searchTerms(input) {
  return String(input || "")
    .split(/[\s,./·|()[\]{}"'`~!?]+/)
    .map((t) => (t.length >= 3 ? t.replace(PARTICLE, "") : t))
    .map((t) => t.trim())
    .filter((t) => t.length >= 2 && !SEARCH_STOPWORDS.has(t))
    .slice(0, 5);
}
